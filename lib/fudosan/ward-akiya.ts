export type WardAkiya = {
  ward: string
  rate: Record<AkiyaYear, number>       // 空き家率 %
  rentRate: Record<AkiyaYear, number>   // 賃貸用の空き家 ÷ 住宅総数 %
  change5y: number                      // 2018→2023 の空き家率の差（pt）
  rentChange5y: number
  change15y: number                     // 2008→2023
  trend: '上昇' | '横ばい' | '低下'
  rankHigh: number                      // 2023年の空き家率が23区で高い順（1=最も高い）
  rankRise: number                      // 5年の上昇幅が大きい順（1=最も上昇）
}

const r1 = (n: number) => Math.round(n * 100) / 100

function build(ward: string): WardAkiya {
  const src = WARD_AKIYA[ward]
  const rate = {} as Record<AkiyaYear, number>
  const rentRate = {} as Record<AkiyaYear, number>
  for (const y of AKIYA_YEARS) {
    const [t, v, rv] = src[y]
    rate[y] = r1((v / t) * 100)
    rentRate[y] = r1((rv / t) * 100)
  }
  const change5y = r1(rate[2023] - rate[2018])
  // 画面は小数1桁で出すので、判定も表示と同じ値で行う（+0.98 と +1.01 が同じ「+1.0」なのに判定が割れないように）
  const shown = Math.round(change5y * 10) / 10
  return {
    ward, rate, rentRate, change5y,
    rentChange5y: r1(rentRate[2023] - rentRate[2018]),
    change15y: r1(rate[2023] - rate[2008]),
    trend: shown >= AKIYA_FLAT_PT ? '上昇' : shown <= -AKIYA_FLAT_PT ? '低下' : '横ばい',
    rankHigh: 0, rankRise: 0,
  }
}

export const WARD_AKIYA_LIST: WardAkiya[] = (() => {
  const list = Object.keys(WARD_AKIYA).filter(w => w !== '特別区部').map(build)
  ;[...list].sort((a, b) => b.rate[2023] - a.rate[2023]).forEach((w, i) => { w.rankHigh = i + 1 })
  ;[...list].sort((a, b) => b.change5y - a.change5y).forEach((w, i) => { w.rankRise = i + 1 })
  return list
})()

export const TOKUBETSU_KUBU: WardAkiya = build('特別区部')

/** 住所などの文字列から23区を探して、その区の空き家データを返す */
export function findWardAkiya(text: string | null | undefined): WardAkiya | null {
  if (!text) return null
  // 「横浜市港北区」を「北区」と取り違えないよう、区名の直前が漢字なら一致とみなさない（「東京都」の「都」は除く）
  const isKanji = (c: string) => /[\u4e00-\u9fff々]/.test(c)
  const matches = (w: string) => {
    for (let i = text.indexOf(w); i >= 0; i = text.indexOf(w, i + 1)) {
      const prev = text[i - 1]
      if (i === 0 || !isKanji(prev) || prev === '都') return true
    }
    return false
  }
  return WARD_AKIYA_LIST.find(w => matches(w.ward)) ?? null
}

/** 通知・画面に出す1行 */
export function wardAkiyaNote(w: WardAkiya): string {
  const sign = (n: number) => `${n > 0 ? '+' : ''}${n.toFixed(1)}`
  return `${w.ward}の空き家率 ${w.rate[2023].toFixed(1)}%（2018年 ${w.rate[2018].toFixed(1)}% → ${sign(w.change5y)}pt・${w.trend}／23区で高い順 ${w.rankHigh}位）` +
    `・賃貸用の空き家 ${w.rentRate[2023].toFixed(1)}%（${sign(w.rentChange5y)}pt）`
}
