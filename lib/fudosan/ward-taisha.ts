// 区別の「代謝率」（1年間に人口の何%が入れ替わったか）
//
//   代謝率 = (転入者数 + 転出者数) ÷ 年初の人口
//   転入・転出は国内（他市区町村との移動）と国外の両方を含む。区から区への引越しも1件として数える。
//
// 人の出入りが多い区ほど、空室がすぐ埋まり、更新のたびに賃料を相場に合わせやすい。
// 23区では地価の上がり方とも素直に連動している（下の LAND_R8 との相関 r≒0.63・2025年）。
// 物件判定には「表示だけ」。点数には入れない（区単位の指標で、物件ごとの差がつかないため）。
//
// 出典: 総務省「住民基本台帳に基づく人口、人口動態及び世帯数」【総計】市区町村別
//   令和4〜8年1月1日現在（各年の前年1年間の人口動態）。いずれも Excel を n8n 経由で取得して集計。
//   2022: main_content/000829117.xlsx  2023: 000892856.xlsx  2024: 000959256.xlsx
//   2025: 001023714.xlsx  2026: 001083789.xlsx
//   年初の人口 = 翌年1月1日の人口 − その年の増減数
//   検算: 2025年の品川区の国内転入 31,461人は「住民基本台帳人口移動報告」第11-1表の 31,468人とほぼ一致
//
// 地価: 東京都「令和8年地価公示 区市町村別用途別対前年変動率」住宅地（令和8年1月1日時点・%）

