export type WardTaisha = {
  ward: string
  rate: Record<TaishaYear, number>   // 代謝率 %
  inRate: number                     // 直近年の転入率 %
  outRate: number                    // 直近年の転出率 %
  netRate: number                    // 直近年の転入超過率 %（社会増）
  change4y: number                   // 2021→2025 の代謝率の差（pt）
  land: number | null                // 地価公示 住宅地の変動率 %
  rank: number                       // 直近年の代謝率が23区で高い順（1=最も高い）
}

const r1 = (n: number) => Math.round(n * 10) / 10

function build(ward: string): WardTaisha {
  const src = WARD_FLOWS[ward]
  const rate = {} as Record<TaishaYear, number>
  for (const y of TAISHA_YEARS) {
    const [pop, iD, iF, oD, oF] = src[y]
    rate[y] = r1(((iD + iF + oD + oF) / pop) * 100)
  }
  const [pop, iD, iF, oD, oF] = src[TAISHA_LATEST]
  return {
    ward, rate,
    inRate: r1(((iD + iF) / pop) * 100),
    outRate: r1(((oD + oF) / pop) * 100),
    netRate: r1(((iD + iF - oD - oF) / pop) * 100),
    change4y: r1(rate[TAISHA_LATEST] - rate[2021]),
    land: LAND_R8[ward] ?? null,
    rank: 0,
  }
}

export const WARD_TAISHA_LIST: WardTaisha[] = (() => {
  const list = Object.keys(WARD_FLOWS).map(build)
  ;[...list].sort((a, b) => b.rate[TAISHA_LATEST] - a.rate[TAISHA_LATEST]).forEach((w, i) => { w.rank = i + 1 })
  return list
})()

export const TAISHA_MEDIAN: number = (() => {
  const s = WARD_TAISHA_LIST.map(w => w.rate[TAISHA_LATEST]).sort((a, b) => a - b)
  return s[Math.floor(s.length / 2)]
})()

/** 代謝率と地価変動率の相関係数（23区） */
export const TAISHA_LAND_CORR: number = (() => {
  const xs = WARD_TAISHA_LIST.filter(w => w.land !== null)
  const mx = xs.reduce((s, w) => s + w.rate[TAISHA_LATEST], 0) / xs.length
  const my = xs.reduce((s, w) => s + (w.land as number), 0) / xs.length
  let sxy = 0, sxx = 0, syy = 0
  for (const w of xs) {
    const dx = w.rate[TAISHA_LATEST] - mx, dy = (w.land as number) - my
    sxy += dx * dy; sxx += dx * dx; syy += dy * dy
  }
  return Math.round((sxy / Math.sqrt(sxx * syy)) * 100) / 100
})()

/** 住所などの文字列から23区を探す（ward-akiya と同じ規則。「横浜市港北区」を「北区」と取り違えない） */
export function findWardTaisha(text: string | null | undefined): WardTaisha | null {
  if (!text) return null
  const isKanji = (c: string) => /[一-鿿々]/.test(c)
  const matches = (w: string) => {
    for (let i = text.indexOf(w); i >= 0; i = text.indexOf(w, i + 1)) {
      const prev = text[i - 1]
      if (i === 0 || !isKanji(prev) || prev === '都') return true
    }
    return false
  }
  return WARD_TAISHA_LIST.find(w => matches(w.ward)) ?? null
}

/** 通知・画面に出す1行 */
export function wardTaishaNote(w: WardTaisha): string {
  const sign = (n: number) => `${n > 0 ? '+' : ''}${n.toFixed(1)}`
  return `${w.ward}の代謝率 ${w.rate[TAISHA_LATEST].toFixed(1)}%（${TAISHA_LATEST}年・23区で高い順 ${w.rank}位／中央値 ${TAISHA_MEDIAN.toFixed(1)}%）` +
    `・転入 ${w.inRate.toFixed(1)}% 転出 ${w.outRate.toFixed(1)}%・2021年から ${sign(w.change4y)}pt`
}
